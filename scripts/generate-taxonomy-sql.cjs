#!/usr/bin/env node
/* eslint-disable @typescript-eslint/no-require-imports -- Plain Node script. */
/**
 * Generates the Phase 2 taxonomy SQL from prisma/taxonomy/categories.json, using
 * the application's own text normaliser, so the migration, the backfill keys and
 * the running code always agree.
 *
 *   node scripts/generate-taxonomy-sql.cjs          write the SQL files
 *   node scripts/generate-taxonomy-sql.cjs --check  exit 1 when they are out of date
 *
 * Writes only files in this repository. Never connects to a database.
 */
const fs = require('node:fs');
const path = require('node:path');
const { loadTs } = require('../tests/load-ts.cjs');

const ROOT = path.resolve(__dirname, '..');
const DATA = path.join(ROOT, 'prisma/taxonomy/categories.json');
const OUT = {
  up: path.join(ROOT, 'prisma/manual-migrations/20261116_phase2_course_taxonomy.sql'),
  preflight: path.join(ROOT, 'prisma/manual-migrations/00_preflight_phase2_taxonomy_readonly.sql'),
};

const { normalizeText } = loadTs('../src/lib/search-normalize.ts');

const sql = value => value === null || value === undefined ? 'NULL' : `'${String(value).replace(/'/g, "''")}'`;
const sqlArray = values => values.length ? `ARRAY[${values.map(sql).join(', ')}]::TEXT[]` : `ARRAY[]::TEXT[]`;

/** Flattened rows, main categories first, with deterministic ids and order. */
function rows(data = JSON.parse(fs.readFileSync(DATA, 'utf8'))) {
  const out = [];
  data.categories.forEach((main, i) => {
    out.push({ ...main, id: `cat_${main.slug}`, parentId: null, order: (i + 1) * 10 });
    (main.children || []).forEach((child, j) => {
      out.push({ ...child, id: `cat_${child.slug}`, parentId: `cat_${main.slug}`, order: (j + 1) * 10 });
    });
  });
  return out.map(row => ({ ...row, normalizedName: normalizeText(row.name), aliases: row.aliases || [] }));
}

/**
 * Backfill keys: normalised category name (priority 1) and aliases (priority 2).
 * A legacy course text is mapped only when it equals exactly one key.
 */
function keys(all) {
  const list = [];
  for (const row of all) {
    list.push([row.normalizedName, row.id, 1]);
    for (const alias of row.aliases) list.push([normalizeText(alias), row.id, 2]);
  }
  return list;
}

/** PostgreSQL version of normalizeText() for legacy course text (verified by tests). */
const NORM = column => `btrim(regexp_replace(translate(regexp_replace(lower(normalize(${column}, NFKC)), `
  + `'[\\u064B-\\u065F\\u0670\\u06D6-\\u06ED\\u0640]', '', 'g'), `
  + `'أإآٱىؤئة٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹', 'اااايويه01234567890123456789'), `
  + `'[^0-9a-z\\u0621-\\u063A\\u0641-\\u064A\\u066E-\\u06D3\\u06FA-\\u06FF]+', ' ', 'g'))`;

const keysCte = all => `taxonomy_keys(key, category_id, priority) AS (VALUES\n${keys(all)
  .map(([key, id, priority]) => `    (${sql(key)}, ${sql(id)}, ${priority})`).join(',\n')}\n  )`;

const MATCH = all => `${keysCte(all)},
  course_keys AS (
    SELECT c."id" AS course_id, ${NORM('c."category"')} AS key
    FROM "Course" c WHERE c."categoryId" IS NULL
  ),
  candidates AS (
    SELECT ck.course_id, k.category_id, k.priority FROM course_keys ck JOIN taxonomy_keys k ON k.key = ck.key
  ),
  best AS (
    SELECT course_id, min(priority) AS priority FROM candidates GROUP BY course_id
  ),
  chosen AS (
    SELECT c.course_id, min(c.category_id) AS category_id, count(DISTINCT c.category_id) AS matches
    FROM candidates c JOIN best b ON b.course_id = c.course_id AND b.priority = c.priority
    GROUP BY c.course_id
  )`;

function upSql(all) {
  const insert = row => `  (${[sql(row.id), sql(row.slug), sql(row.name), sql(row.nameEn ?? null), sql(row.normalizedName),
    sqlArray(row.aliases), sql(row.parentId), row.order, 'true', 'now()', 'now()'].join(', ')})`;
  const mains = all.filter(row => !row.parentId);
  const subs = all.filter(row => row.parentId);
  return `-- KQ Academy, Phase 2: course taxonomy (main categories + subcategories), course
-- tags and training type. GENERATED by scripts/generate-taxonomy-sql.cjs from
-- prisma/taxonomy/categories.json - edit those, then regenerate.
--
-- Safe on existing data and safe to run more than once:
--   * additive only: one new table, three new columns on "Course" (nullable, or with
--     an empty default), one foreign key and two indexes. Nothing is dropped.
--   * "Course"."category" (the text every page shows) is NOT modified.
--   * default categories are inserted with ON CONFLICT DO NOTHING, so a re-run never
--     overwrites a category an administrator renamed, moved or deactivated.
--   * backfill: a course is linked ("categoryId") only when its current category text,
--     after Arabic spelling normalisation, equals exactly one category name or alias.
--     Courses already linked, ambiguous texts and unknown texts are left unchanged
--     (they stay searchable by their text). Review 00_preflight_phase2_taxonomy_readonly.sql
--     first: it lists every category text and what it would be linked to.
--   * "updatedAt" of courses is not touched.
-- Rollback: rollback/20261116_phase2_course_taxonomy_DOWN.sql (only if abandoned for good;
-- the previous release runs correctly with these additions in place).
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS "Category" (
  "id"             TEXT NOT NULL,
  "slug"           TEXT NOT NULL,
  "name"           TEXT NOT NULL,
  "nameEn"         TEXT,
  "normalizedName" TEXT NOT NULL,
  "aliases"        TEXT[] DEFAULT ARRAY[]::TEXT[],
  "parentId"       TEXT,
  "order"          INTEGER NOT NULL DEFAULT 0,
  "isActive"       BOOLEAN NOT NULL DEFAULT true,
  "createdAt"      TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt"      TIMESTAMP(3) NOT NULL,
  CONSTRAINT "Category_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX IF NOT EXISTS "Category_slug_key" ON "Category"("slug");
CREATE UNIQUE INDEX IF NOT EXISTS "Category_normalizedName_key" ON "Category"("normalizedName");
CREATE INDEX IF NOT EXISTS "Category_parentId_idx" ON "Category"("parentId");
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'Category_parentId_fkey') THEN
    ALTER TABLE "Category" ADD CONSTRAINT "Category_parentId_fkey" FOREIGN KEY ("parentId")
      REFERENCES "Category"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
  END IF;
END $$;

-- Metadata-only on PostgreSQL 11+: no table rewrite.
ALTER TABLE "Course" ADD COLUMN IF NOT EXISTS "categoryId" TEXT;
ALTER TABLE "Course" ADD COLUMN IF NOT EXISTS "tags" TEXT[] DEFAULT ARRAY[]::TEXT[];
ALTER TABLE "Course" ADD COLUMN IF NOT EXISTS "trainingType" TEXT;
CREATE INDEX IF NOT EXISTS "Course_categoryId_idx" ON "Course"("categoryId");
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'Course_categoryId_fkey') THEN
    ALTER TABLE "Course" ADD CONSTRAINT "Course_categoryId_fkey" FOREIGN KEY ("categoryId")
      REFERENCES "Category"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
  END IF;
END $$;

-- Default taxonomy: ${mains.length} main categories, ${subs.length} subcategories.
INSERT INTO "Category" ("id", "slug", "name", "nameEn", "normalizedName", "aliases", "parentId", "order", "isActive", "createdAt", "updatedAt") VALUES
${mains.map(insert).join(',\n')}
ON CONFLICT DO NOTHING;
INSERT INTO "Category" ("id", "slug", "name", "nameEn", "normalizedName", "aliases", "parentId", "order", "isActive", "createdAt", "updatedAt") VALUES
${subs.map(insert).join(',\n')}
ON CONFLICT DO NOTHING;

-- Backfill: link courses whose text names exactly one category (by name first, then alias).
WITH ${MATCH(all)}
UPDATE "Course" AS course SET "categoryId" = chosen.category_id
FROM chosen
WHERE chosen.course_id = course."id" AND chosen.matches = 1 AND course."categoryId" IS NULL
  AND EXISTS (SELECT 1 FROM "Category" cat WHERE cat."id" = chosen.category_id);

COMMIT;
`;
}

function preflightSql(all) {
  return `-- KQ Academy, Phase 2 taxonomy preflight. READ ONLY: run before
-- 20261116_phase2_course_taxonomy.sql. GENERATED by scripts/generate-taxonomy-sql.cjs.
--
-- Lists every distinct course category text, how many courses (and published courses)
-- use it, and the category the migration's backfill would link it to:
--   mapped_to     the default category id it will be linked to
--   unmapped      no category name or alias matches: the course keeps its text and
--                 stays searchable; an administrator can create/choose a category later
--   ambiguous     the text matches several categories: left unlinked on purpose
-- Works before the migration (the "Course"."categoryId" column does not exist yet).
BEGIN TRANSACTION READ ONLY;

WITH ${keysCte(all)},
  texts AS (
    SELECT c."category" AS category_text, ${NORM('c."category"')} AS key,
      count(*) AS courses, count(*) FILTER (WHERE c."status" = 'PUBLISHED') AS published
    FROM "Course" c GROUP BY c."category"
  ),
  candidates AS (
    SELECT t.category_text, k.category_id, k.priority FROM texts t JOIN taxonomy_keys k ON k.key = t.key
  ),
  best AS (
    SELECT category_text, min(priority) AS priority FROM candidates GROUP BY category_text
  ),
  chosen AS (
    SELECT c.category_text, min(c.category_id) AS category_id, count(DISTINCT c.category_id) AS matches
    FROM candidates c JOIN best b ON b.category_text = c.category_text AND b.priority = c.priority
    GROUP BY c.category_text
  )
SELECT t.category_text, t.courses, t.published,
  CASE WHEN ch.matches IS NULL THEN 'unmapped' WHEN ch.matches > 1 THEN 'ambiguous' ELSE 'mapped_to' END AS result,
  CASE WHEN ch.matches = 1 THEN ch.category_id END AS category_id
FROM texts t LEFT JOIN chosen ch ON ch.category_text = t.category_text
ORDER BY result DESC, t.courses DESC, t.category_text;

-- Totals.
SELECT count(*) AS courses, count(*) FILTER (WHERE "status" = 'PUBLISHED') AS published FROM "Course";

ROLLBACK;
`;
}

function generate() {
  const all = rows();
  return { [OUT.up]: upSql(all), [OUT.preflight]: preflightSql(all) };
}

module.exports = { rows, keys, NORM, generate, OUT };

if (require.main === module) {
  const files = generate();
  if (process.argv.includes('--check')) {
    const stale = Object.entries(files).filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text);
    for (const [file] of stale) console.error(`Out of date: ${path.relative(ROOT, file)}`);
    process.exit(stale.length ? 1 : 0);
  }
  for (const [file, text] of Object.entries(files)) {
    fs.writeFileSync(file, text);
    console.log(`Wrote ${path.relative(ROOT, file)}`);
  }
}
